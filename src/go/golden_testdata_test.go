package ckv

// 共享黄金向量测试（testdata/*.db）。
//
// 这些文件由 tools/gen_testdata.py 按 v3.2 规范**独立于三种实现**生成。
// 本测试做两件事：
//   1. 读取外部生成的文件 → 断言解析出的内容正确（证明互操作性）
//   2. 用本实现重新生成相同内容 → 断言字节与外部文件**完全一致**
//      （证明确定性序列化，字节级兼容）
//
// Rust / .NET 有同构测试，三者必须通过同一套 testdata。

import (
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"math"
	"os"
	"path/filepath"
	"testing"
)

func testdataDir() string {
	return filepath.Join("..", "..", "testdata")
}

func readVector(t *testing.T, name string) []byte {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(testdataDir(), name))
	if err != nil {
		t.Fatalf("cannot read %s: %v", name, err)
	}
	return data
}

func shaHexOf(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

const (
	emptySha     = "06cbf30c0cd3b3c512bc42b8d221b7e51e675a269ebbc69a62007a20e02be328"
	singlePutSha = "f4b9d73bece38e54376d3c412e1b5fa4353811d33ba33cbd073df54aecbb224a"
)

// 空库：32 字节、SHA-256 与规范一致、可被打开且为空
func TestGoldenTestdataEmptyV3(t *testing.T) {
	data := readVector(t, "empty_v3.db")
	if len(data) != 32 {
		t.Fatalf("empty_v3.db must be 32 bytes, got %d", len(data))
	}
	if got := shaHexOf(data); got != emptySha {
		t.Fatalf("empty_v3.db SHA mismatch: got %s", got)
	}

	dir := t.TempDir()
	p := filepath.Join(dir, "copy.db")
	if err := os.WriteFile(p, data, 0600); err != nil {
		t.Fatal(err)
	}

	db, err := Open(p)
	if err != nil {
		t.Fatal(err)
	}
	if n, _ := db.Count(""); n != 0 {
		t.Fatalf("empty vector count = %d", n)
	}
	if len(db.Namespaces()) != 0 {
		t.Fatalf("empty vector namespaces = %v", db.Namespaces())
	}
	if s := db.Stats(); s.CurrentMaxTxID != 0 {
		t.Fatalf("empty vector CurrentMaxTxID = %d", s.CurrentMaxTxID)
	}

	// 再落盘一次必须还原同样的 32 字节
	if err := db.Flush(); err != nil {
		t.Fatal(err)
	}
	after, _ := os.ReadFile(p)
	if !bytes.Equal(after, data) {
		t.Fatal("empty round-trip must be byte-identical")
	}
	_ = db.Close()
}

// 单条 put：80 字节、SHA-256 与规范一致、内容与本地生成字节完全相同
func TestGoldenTestdataSinglePutV3(t *testing.T) {
	data := readVector(t, "single_put_v3.db")
	if len(data) != 80 {
		t.Fatalf("single_put_v3.db must be 80 bytes, got %d", len(data))
	}
	if got := shaHexOf(data); got != singlePutSha {
		t.Fatalf("single_put_v3.db SHA mismatch: got %s", got)
	}

	dir := t.TempDir()

	// 1) 解析外部文件
	p := filepath.Join(dir, "single.db")
	if err := os.WriteFile(p, data, 0600); err != nil {
		t.Fatal(err)
	}
	db, err := Open(p)
	if err != nil {
		t.Fatal(err)
	}
	if v, _ := db.GetString("", "hello"); v == nil || *v != "world" {
		t.Fatalf("golden string = %v", v)
	}
	if n, _ := db.Count(""); n != 1 {
		t.Fatalf("golden count = %d", n)
	}
	_ = db.Close()

	// 2) 本地重新生成，字节必须相同
	p2 := filepath.Join(dir, "regen.db")
	db2, err := Open(p2)
	if err != nil {
		t.Fatal(err)
	}
	if err := db2.PutString("", "hello", "world"); err != nil {
		t.Fatal(err)
	}
	_ = db2.Close()
	regen, _ := os.ReadFile(p2)
	if !bytes.Equal(regen, data) {
		t.Fatalf("locally generated bytes differ:\n got %s\nwant %s",
			hex.EncodeToString(regen), hex.EncodeToString(data))
	}
}

// 5 种 ValueType + 多命名空间：解析正确且本地重新生成字节相同
func TestGoldenTestdataMultiTypesV3(t *testing.T) {
	data := readVector(t, "multi_types_v3.db")
	dir := t.TempDir()
	p := filepath.Join(dir, "multi.db")
	if err := os.WriteFile(p, data, 0600); err != nil {
		t.Fatal(err)
	}

	db, err := Open(p)
	if err != nil {
		t.Fatal(err)
	}
	if b, _ := db.GetBytes("", "bytes"); !bytes.Equal(b, []byte{0x00, 0x01, 0xFE, 0xFF}) {
		t.Fatalf("bytes = %v", b)
	}
	if v, _ := db.GetString("", "str"); v == nil || *v != "你好" {
		t.Fatalf("str = %v", v)
	}
	if v, _ := db.GetInt64("", "i64"); v == nil || *v != -1234567890123456789 {
		t.Fatalf("i64 = %v", v)
	}
	if v, _ := db.GetFloat64("", "f64"); v == nil || *v != 3.141592653589793 {
		t.Fatalf("f64 = %v", v)
	}
	nan, _ := db.GetFloat64("", "f64nan")
	if nan == nil || !math.IsNaN(*nan) {
		t.Fatalf("f64nan = %v", nan)
	}
	if got := EncodeFloat64(*nan); binary.LittleEndian.Uint64(got) != CanonicalQuietNaNBits {
		t.Fatal("NaN must be canonicalised")
	}
	if v, _ := db.GetBool("", "bool_t"); v == nil || *v != true {
		t.Fatalf("bool_t = %v", v)
	}
	if v, _ := db.GetBool("", "bool_f"); v == nil || *v != false {
		t.Fatalf("bool_f = %v", v)
	}
	if v, _ := db.GetBool("cfg", "enabled"); v == nil || *v != true {
		t.Fatalf("cfg.enabled = %v", v)
	}
	if v, _ := db.GetInt64("cfg", "limit"); v == nil || *v != 1000 {
		t.Fatalf("cfg.limit = %v", v)
	}
	if v, _ := db.GetString("users", "u1"); v == nil || *v != "alice" {
		t.Fatalf("users.u1 = %v", v)
	}
	ns := db.Namespaces()
	if len(ns) != 3 || ns[0] != "" || ns[1] != "cfg" || ns[2] != "users" {
		t.Fatalf("namespaces = %v", ns)
	}
	if s := db.Stats(); s.TotalEntries != 10 {
		t.Fatalf("total entries = %d", s.TotalEntries)
	}
	_ = db.Close()

	// 本地重新生成
	p2 := filepath.Join(dir, "multi_regen.db")
	db2, err := Open(p2)
	if err != nil {
		t.Fatal(err)
	}
	err = db2.Batch(func(b *BatchWriter) error {
		_ = b.PutBytes("", "bytes", []byte{0x00, 0x01, 0xFE, 0xFF})
		_ = b.PutString("", "str", "你好")
		_ = b.PutInt64("", "i64", -1234567890123456789)
		_ = b.PutFloat64("", "f64", 3.141592653589793)
		_ = b.PutFloat64("", "f64nan", nanValue())
		_ = b.PutBool("", "bool_t", true)
		_ = b.PutBool("", "bool_f", false)
		_ = b.PutBool("cfg", "enabled", true)
		_ = b.PutInt64("cfg", "limit", 1000)
		_ = b.PutString("users", "u1", "alice")
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	_ = db2.Close()
	regen, _ := os.ReadFile(p2)
	if !bytes.Equal(regen, data) {
		t.Fatalf("locally generated bytes differ:\n got %s\nwant %s",
			hex.EncodeToString(regen), hex.EncodeToString(data))
	}
}

// 非 ASCII 命名空间/键：锁定 UTF-8 无符号字节序
func TestGoldenTestdataUnicodeOrderV3(t *testing.T) {
	data := readVector(t, "unicode_order_v3.db")
	dir := t.TempDir()
	p := filepath.Join(dir, "uni.db")
	if err := os.WriteFile(p, data, 0600); err != nil {
		t.Fatal(err)
	}

	db, err := Open(p)
	if err != nil {
		t.Fatal(err)
	}
	ns := db.Namespaces()
	wantNs := []string{"", "cf", "é", "中文"}
	if len(ns) != len(wantNs) {
		t.Fatalf("namespaces = %v, want %v", ns, wantNs)
	}
	for i := range wantNs {
		if ns[i] != wantNs[i] {
			t.Fatalf("namespaces[%d] = %q, want %q (full %v)", i, ns[i], wantNs[i], ns)
		}
	}

	keys, _ := db.Keys("")
	wantKeys := []string{"a", "z", "\uE000", "\U0001F600"}
	if len(keys) != len(wantKeys) {
		t.Fatalf("keys = %v, want %v", keys, wantKeys)
	}
	for i := range wantKeys {
		if keys[i] != wantKeys[i] {
			t.Fatalf("keys[%d] = %q, want %q (full %v)", i, keys[i], wantKeys[i], keys)
		}
	}
	_ = db.Close()

	// 本地重新生成
	p2 := filepath.Join(dir, "uni_regen.db")
	db2, err := Open(p2)
	if err != nil {
		t.Fatal(err)
	}
	err = db2.Batch(func(b *BatchWriter) error {
		for _, kv := range [][3]string{
			{"", "a", "1"}, {"", "z", "2"}, {"", "\uE000", "3"}, {"", "\U0001F600", "4"},
			{"é", "k", "5"}, {"中文", "k", "6"}, {"cf", "k", "7"},
		} {
			_ = b.PutString(kv[0], kv[1], kv[2])
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	_ = db2.Close()
	regen, _ := os.ReadFile(p2)
	if !bytes.Equal(regen, data) {
		t.Fatalf("locally generated bytes differ:\n got %s\nwant %s",
			hex.EncodeToString(regen), hex.EncodeToString(data))
	}
}

// 直接解码帧头字段核对（不经过 DB 实现）
func TestGoldenTestdataFrameHeaderLayout(t *testing.T) {
	data := readVector(t, "single_put_v3.db")
	if string(data[0:8]) != "UKVDB003" {
		t.Fatal("file magic mismatch")
	}
	if binary.LittleEndian.Uint16(data[8:10]) != 3 || binary.LittleEndian.Uint16(data[10:12]) != 3 {
		t.Fatal("format version mismatch")
	}
	if binary.LittleEndian.Uint32(data[32:36]) != FrameMagic {
		t.Fatal("frame magic mismatch")
	}
	if binary.LittleEndian.Uint64(data[40:48]) != 1 {
		t.Fatal("TxID must be 1")
	}
	if binary.LittleEndian.Uint32(data[48:52]) != 1 {
		t.Fatal("OpCount must be 1")
	}
	if binary.LittleEndian.Uint32(data[52:56]) != 20 {
		t.Fatal("PayloadLen must be 20")
	}
	if data[60] != OpPut || data[61] != ValTypeString {
		t.Fatal("entry op/type mismatch")
	}
	if binary.LittleEndian.Uint16(data[62:64]) != 0 {
		t.Fatal("NsLen must be 0")
	}
	if binary.LittleEndian.Uint16(data[64:66]) != 5 {
		t.Fatal("KeyLen must be 5")
	}
	if binary.LittleEndian.Uint32(data[66:70]) != 5 {
		t.Fatal("ValLen must be 5")
	}
	if string(data[70:75]) != "hello" || string(data[75:80]) != "world" {
		t.Fatal("key/value bytes mismatch")
	}
}

// MANIFEST.txt 必须与磁盘上的实际文件一致（防止向量被改而清单未更新）
func TestGoldenTestdataManifestMatches(t *testing.T) {
	manifestBytes, err := os.ReadFile(filepath.Join(testdataDir(), "MANIFEST.txt"))
	if err != nil {
		t.Fatal(err)
	}
	manifest := string(manifestBytes)
	for _, name := range []string{
		"empty_v3.db", "single_put_v3.db", "multi_types_v3.db", "unicode_order_v3.db",
	} {
		digest := shaHexOf(readVector(t, name))
		if !bytes.Contains([]byte(manifest), []byte(digest)) {
			t.Fatalf("%s hash %s missing from MANIFEST.txt", name, digest)
		}
	}
}

func nanValue() float64 {
	return math.NaN()
}
